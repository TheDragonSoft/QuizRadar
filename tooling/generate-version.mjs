#!/usr/bin/env node
/**
 * Single source of truth for versions: tooling/version.json.
 *
 * Stamps every version sink:
 *   1. apps/web/package.json                       #version
 *   2. apps/desktop/src-tauri/tauri.conf.json      #version
 *   3. root Cargo.toml                             [workspace.package].version
 *   4. apps/mobile-android/app/build.gradle.kts    versionName + versionCode
 *      (versionCode = major*10000 + minor*100 + patch; pre-release suffix ignored)
 *   5. apps/web/src/generated/version.ts           APP_VERSION + SW cache key
 *      (apps/web/vite.config.ts additionally defines __APP_VERSION__ at build
 *       time by reading tooling/version.json directly, so it cannot go stale)
 *
 * Run `node tooling/generate-version.mjs --check` in CI — exits 1 when any
 * sink is stale, with instructions to re-run without --check.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));

// `--root <dir>` repoints every sink lookup at another tree. The version
// pipeline test uses it to exercise the generator against a throwaway copy of
// the sinks instead of rewriting tracked files in the working tree.
const rootArgIndex = process.argv.indexOf("--root");
const repoRoot =
  rootArgIndex !== -1 && process.argv[rootArgIndex + 1]
    ? path.resolve(process.cwd(), process.argv[rootArgIndex + 1])
    : path.resolve(scriptDir, "..");

const versionRaw = JSON.parse(
  readFileSync(path.join(repoRoot, "tooling/version.json"), "utf8"),
).version;
const semver = /^(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.\-+]+))?$/.exec(String(versionRaw));
if (!semver) {
  console.error(`tooling/version.json: "${versionRaw}" is not semver (MAJOR.MINOR.PATCH[-pre])`);
  process.exit(1);
}
const [, major, minor, patch] = semver;
const version = String(versionRaw);
const versionCode = Number(major) * 10000 + Number(minor) * 100 + Number(patch);

const generatedVersionTs = `// AUTO-GENERATED by tooling/generate-version.mjs from tooling/version.json — do not edit.\nexport const APP_VERSION = "${version}";\nexport const SW_CACHE_KEY_PREFIX = "quizradar-v${version}";\n`;

/** Every sink: name + read() returning the stamped content it must have. */
const sinks = [
  {
    name: "apps/web/package.json (version)",
    read: () => {
      const pkg = JSON.parse(readFileSync(path.join(repoRoot, "apps/web/package.json"), "utf8"));
      return JSON.stringify({ ...pkg, version }, null, 2) + "\n";
    },
  },
  {
    name: "apps/desktop/src-tauri/tauri.conf.json (version)",
    read: () => {
      const conf = JSON.parse(
        readFileSync(path.join(repoRoot, "apps/desktop/src-tauri/tauri.conf.json"), "utf8"),
      );
      return JSON.stringify({ ...conf, version }, null, 2) + "\n";
    },
  },
  {
    name: "Cargo.toml ([workspace.package].version)",
    read: () => {
      const content = readFileSync(path.join(repoRoot, "Cargo.toml"), "utf8");
      if (!/^version = "[^"]*"/m.test(content)) {
        throw new Error('Cargo.toml: pattern `version = "..."` not found');
      }
      return content.replace(/^(version = ")[^"]*(")$/m, `$1${version}$2`);
    },
  },
  {
    name: "apps/mobile-android/app/build.gradle.kts (versionName/versionCode)",
    read: () => {
      const content = readFileSync(
        path.join(repoRoot, "apps/mobile-android/app/build.gradle.kts"),
        "utf8",
      );
      if (
        !/^\s*versionCode = \d+$/m.test(content) ||
        !/^\s*versionName = "[^"]*"$/m.test(content)
      ) {
        throw new Error("build.gradle.kts: versionCode or versionName pattern not found");
      }
      return content
        .replace(/^(\s*versionCode = )\d+$/m, `$1${versionCode}`)
        .replace(/^(\s*versionName = ")[^"]*(")$/m, `$1${version}$2`);
    },
  },
  {
    name: "apps/web/src/generated/version.ts (APP_VERSION + SW cache key)",
    read: () => generatedVersionTs,
  },
];

// Registrations with explicit paths — resolved lazily so `--check` never writes.
const sinkPaths = [
  "apps/web/package.json",
  "apps/desktop/src-tauri/tauri.conf.json",
  "Cargo.toml",
  "apps/mobile-android/app/build.gradle.kts",
  "apps/web/src/generated/version.ts",
];

const check = process.argv.includes("--check");

// A sink that cannot be read or parsed is a *broken* sink, not a crash of the
// whole generator: one corrupt file must not hide the state of the other four.
// Each failure is reported by name so `--check` stays actionable.
const results = sinks.map((sink, i) => {
  const file = path.join(repoRoot, sinkPaths[i]);
  try {
    const expected = sink.read();
    const current = readFileSync(file, "utf8");
    return {
      name: sink.name,
      file,
      expected,
      current,
      stale: expected !== current,
      error: null,
    };
  } catch (err) {
    return {
      name: sink.name,
      file,
      expected: null,
      current: null,
      stale: true,
      error: err instanceof Error ? err.message : String(err),
    };
  }
});

const stale = results.filter((r) => r.stale);
const broken = results.filter((r) => r.error !== null);

if (check) {
  if (stale.length > 0) {
    console.error(
      "Version sinks stale (run `node tooling/generate-version.mjs --apply`, then re-check):",
    );
    for (const s of stale) {
      console.error(`  - ${s.name} (${s.file})`);
      if (s.error) console.error(`      unreadable sink: ${s.error}`);
    }
    process.exit(1);
  }
  console.log(
    `version ${version} (versionCode ${versionCode}) — all ${results.length} sinks in sync.`,
  );
  process.exit(0);
}

if (broken.length > 0) {
  console.error("Refusing to stamp: these sinks could not be read or parsed:");
  for (const s of broken) console.error(`  - ${s.name} (${s.file}): ${s.error}`);
  process.exit(1);
}

for (const r of results) writeFileSync(r.file, r.expected);
console.log(`stamped ${results.length} version sinks to ${version} (versionCode ${versionCode}).`);
